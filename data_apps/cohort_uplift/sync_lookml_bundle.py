#!/usr/bin/env python3
"""Syncs data_apps/cohort_uplift/app.js into lookml/data_apps/cohort_uplift.js for Looker manifest.lkml."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data_apps" / "cohort_uplift" / "app.js"
DST = ROOT / "lookml" / "data_apps" / "cohort_uplift.js"


def main() -> None:
    code = SRC.read_text(encoding="utf-8")
    DST.parent.mkdir(parents=True, exist_ok=True)
    # ponytail: Looker's extension.loader mounts `file:` bundles with `crossorigin="use-credentials"`, which
    # dynamic `import()` inherits (breaking `ACAO: *` on gstatic). Appending a fresh `<script type="module" src="blob:...">`
    # without `crossorigin` resets the module graph's credentials mode to `"same-origin"` while keeping CSP `strict-dynamic` trust.
    wrapped = (
        "// Generated by data_apps/cohort_uplift/sync_lookml_bundle.py — edit data_apps/cohort_uplift/app.js instead.\n"
        "(function () {\n"
        "  const u = URL.createObjectURL(new Blob([" + json.dumps(code) + "], { type: 'text/javascript' }));\n"
        "  const s = document.createElement('script');\n"
        "  s.type = 'module';\n"
        "  s.src = u;\n"
        "  s.onload = s.onerror = () => URL.revokeObjectURL(u);\n"
        "  document.head.appendChild(s);\n"
        "})();\n"
    )
    DST.write_text(wrapped, encoding="utf-8")
    print(f"Synced {DST.relative_to(ROOT)} ({len(wrapped):,} bytes)")


if __name__ == "__main__":
    main()
