#!/usr/bin/env python3
"""Syncs every data_apps/<app_id>/app.js into lookml/data_apps/<app_id>.js (or verifies parity with --check)."""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_APPS_DIR = ROOT / "data_apps"
LOOKML_APPS_DIR = ROOT / "lookml" / "data_apps"


def render_wrapper(app_id: str, code: str) -> str:
    # ponytail: Looker's extension.loader mounts `file:` bundles with `crossorigin="use-credentials"`, which
    # dynamic `import()` inherits (breaking `ACAO: *` on gstatic). Appending a fresh `<script type="module" src="blob:...">`
    # without `crossorigin` resets the module graph's credentials mode to `"same-origin"` while keeping CSP `strict-dynamic` trust.
    return (
        f"// Generated by data_apps/sync_lookml_bundles.py from data_apps/{app_id}/app.js — do not edit directly.\n"
        "(function () {\n"
        f"  const u = URL.createObjectURL(new Blob([{json.dumps(code)}], {{ type: 'text/javascript' }}));\n"
        "  const s = document.createElement('script');\n"
        "  s.type = 'module';\n"
        "  s.src = u;\n"
        "  s.onload = s.onerror = () => URL.revokeObjectURL(u);\n"
        "  document.head.appendChild(s);\n"
        "})();\n"
    )


def main(argv: list[str]) -> int:
    check_only = "--check" in argv
    sources = sorted(DATA_APPS_DIR.glob("*/app.js"))
    if not sources:
        sys.stderr.write("No data_apps/*/app.js sources found.\n")
        return 1

    LOOKML_APPS_DIR.mkdir(parents=True, exist_ok=True)
    stale: list[str] = []
    for src in sources:
        app_id = src.parent.name
        dst = LOOKML_APPS_DIR / f"{app_id}.js"
        expected = render_wrapper(app_id, src.read_text(encoding="utf-8"))
        if check_only:
            if not dst.is_file() or dst.read_text(encoding="utf-8") != expected:
                stale.append(app_id)
        else:
            dst.write_text(expected, encoding="utf-8")
            print(f"Synced {dst.relative_to(ROOT)} ({len(expected):,} bytes)")

    if stale:
        sys.stderr.write(
            f"Out-of-sync LookML Data App bundles: {', '.join(stale)}. Run: uv run --script data_apps/sync_lookml_bundles.py\n"
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
